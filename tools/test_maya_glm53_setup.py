"""tools/test_maya_glm53_setup.py - the glm-dsa port, lane C item 6: what the setup (maya.py) writes and offers for
GLM-5.3 (744B, glm-dsa), and GLM-5.3-Flash's exactly as before.

  a) KV streaming: a GLM-5.3 config gets --kv-streaming off (its engine refuses a window below the context, so with on
     every context above 32768 would not start), and a setup again does not keep an older config's on / window;
     the contexts offered are those its whole cache fits on discrete GPUs, counted as the config written will run
     (its --parallel - given now or kept from the config before -, an --env cache format, the HIP / kept reserve)
  d) its own defaults (maya_quants' "glm53": zai-org/GLM-5.3's card), never GLM-5.3-Flash's tuned quant values
  f) the hidden download entry (unsloth's UD-IQ2_M, pinned revision, sha256 a shard), not on Metal
  g) the calibration's own time estimate;  h) GLM-5.3's shipped expert profile when it fits
No GPU, no network, no model.

    python -m unittest tools.test_maya_glm53_setup -v
"""
