class HistoryReuse(unittest.TestCase):
    """With the reasoning sent back, each turn's prompt starts with everything the engine holds (the previous prompt
    and the answer it wrote), so DONE reused covers the previous context; without it, only the previous prompt."""

    def chat(self, send_reasoning: bool, turns: int = 10) -> list[tuple[int, int]]:
        with tempfile.TemporaryDirectory() as d, contextlib.redirect_stdout(io.StringIO()), \
                mock.patch.dict(os.environ, {"STRATA_GPU_RELEASE_S": "0"}):
            tok = glm_tokenizer(Path(d) / "tok")
            answer = "Let me think about this for a while.</think>Here is the answer, with some detail."
            env = dict(os.environ, FAKE_ENGINE_IDS=",".join(map(str, tok.encode(answer))), FAKE_ENGINE_DIR=d)
            eng = StrataEngine(fake_exe(Path(d)), ["--glm-pack", d, "--max-context", "65536"], env=env)
            svc = Service(eng, tok, ChatTemplate(OFFICIAL, glm_dsa=True), model_name="glm-5.3")
            httpd = serve(svc, port=0)
            base = f"http://127.0.0.1:{httpd.server_address[1]}"
            msgs, out, held = [], [], 0
            try:
                for i in range(turns):
                    msgs.append({"role": "user", "content": f"question {i}: tell me more about topic {i}"})
                    # (the fake engine gives the same answer every turn: Maya's loop guard would fold the repeats
                    # out of the history, which is not what this measures)
                    code, body = post(base, "/v1/chat/completions", {"model": "m", "messages": msgs,
                                                                     "max_tokens": 500, "loop_guard": False})
                    self.assertEqual(code, 200, body)
                    m = body["choices"][0]["message"]
                    self.assertEqual(m["content"], "Here is the answer, with some detail.")
                    out.append((eng.last["reused"], held))
                    held = eng.last["prompt_tokens"] + eng.last["generated"]   # what the engine holds now
                    turn = {"role": "assistant", "content": m["content"]}
                    if send_reasoning:
                        turn["reasoning_content"] = m["reasoning_content"]
                    msgs.append(turn)
            finally:
                httpd.shutdown()
                httpd.server_close()
                eng.close()
            return out[1:]

    def test_reasoning_sent_back_reuses_the_previous_context(self):
        for reused, held in self.chat(True):
            self.assertGreaterEqual(reused, 0.9 * held, (reused, held))

    def test_without_it_the_answer_is_read_again(self):
        for reused, held in self.chat(False, turns=3):
            self.assertLess(reused, 0.9 * held, (reused, held))


