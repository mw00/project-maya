class EffortDialect(unittest.TestCase):
    """The thinking levels reach GLM templates whatever their wording (regex dialect detection)."""

    def render(self, path_or_text, effort=None, messages=None, **kw):
        if isinstance(path_or_text, Path):
            t = ChatTemplate(path_or_text, glm_dsa=True)
        else:
            with tempfile.TemporaryDirectory() as d:
                p = Path(d) / "chat_template.jinja"
                p.write_text(path_or_text, encoding="utf-8")
                t = ChatTemplate(p, glm_dsa=True)
        return t, t.render(messages or [{"role": "user", "content": "hi"}], **effort_kwargs(effort), **kw)

    def test_fixture_is_the_official_template(self):
        import hashlib
        self.assertEqual(hashlib.sha256(OFFICIAL.read_bytes()).hexdigest(), GLM53_TEMPLATE_SHA256)

    def test_official_levels(self):
        t, _ = self.render(OFFICIAL)
        self.assertEqual((t.dialect.kind, t.dialect.levels, t.dialect.default), ("glm", ("low", "high", "max"), "max"))
        self.assertTrue(t.glm_effort)
        self.assertIn("the official GLM-5.3 template", t.dialect.describe())
        for effort, line in ((None, "Max"), ("low", "Low"), ("high", "High"), ("max", "Max"), ("medium", "High"),
                             ("xhigh", "Max")):
            with self.subTest(effort=effort):
                _, p = self.render(OFFICIAL, effort)
                self.assertTrue(p.startswith("[gMASK]<sop><|system|>Reasoning Effort: " + line), p[:60])
                self.assertTrue(p.endswith("<|user|>hi<|assistant|><think>"), p[-40:])
        _, off = self.render(OFFICIAL, "none")         # thinking off: Low, and the think block closed empty
        self.assertEqual(system_line(off), "Low")
        self.assertTrue(off.endswith("<|assistant|><think></think>"))

    def test_every_glm53_fixture_renders_three_distinct_levels(self):
        """Three distinct levels, for the official template and the one the UD-IQ2_M GGUF carries (every
        glm-5.3*.jinja in data/glm-dsa/templates)."""
        found = sorted(TEMPLATES.glob("glm-5.3*.jinja"))
        self.assertTrue(found)
        for path in found:
            with self.subTest(template=path.name):
                lines = [system_line(self.render(path, e)[1]) for e in ("low", "high", "max")]
                self.assertEqual(lines, ["Low", "High", "Max"])

    def test_requoted_list_is_still_glm(self):
        src = OFFICIAL.read_text(encoding="utf-8").replace("in ['low', 'high']", 'in ("low","high")')
        self.assertNotIn("reasoning_effort in ['low', 'high']", src)    # Maya's exact phrase is gone
        t, _ = self.render(src)
        self.assertEqual(t.dialect.levels, ("low", "high", "max"))
        self.assertEqual([system_line(self.render(src, e)[1]) for e in ("low", "high", "max")], ["Low", "High", "Max"])

    def test_glm52_high_max_and_its_own_off_form(self):
        t, p = self.render(GLM52)
        self.assertEqual((t.dialect.kind, t.dialect.levels, t.dialect.enable_thinking), ("glm", ("high", "max"), True))
        self.assertEqual(system_line(p), "Max")
        self.assertEqual(system_line(self.render(GLM52, "low")[1]), "High")     # no Low: the next level up
        self.assertEqual(system_line(self.render(GLM52, "high")[1]), "High")
        _, off = self.render(GLM52, "none")              # enable_thinking=false reaches the template
        self.assertEqual(system_line(off), "")
        self.assertTrue(off.endswith("<|assistant|><think></think>"), off[-40:])

    def test_qwen_and_templates_without_levels(self):
        t, _ = self.render(ROOT / "serve/chat_template.jinja")
        self.assertEqual(t.dialect.kind, "qwen")
        self.assertFalse(t.glm_effort)
        plain = "[gMASK]<sop>{% for m in messages %}<|user|>{{ m.content }}{% endfor %}<|assistant|><think>"
        t, p = self.render(plain, "low")
        self.assertEqual(t.dialect.kind, "none")
        self.assertIn("does not read reasoning_effort", t.dialect.describe())
        self.assertEqual(p, "[gMASK]<sop><|user|>hi<|assistant|><think>")

    def test_dialect_of_the_inline_mock_is_unchanged(self):
        # the shape serve/test_server.py's GlmThinkingLevels uses (Maya's own GLM-5.3-Flash test)
        src = ("[gMASK]{%- set effective_reasoning_effort = reasoning_effort if reasoning_effort is defined and "
               "reasoning_effort in ['low', 'high'] else 'max' -%}E={{ effective_reasoning_effort }}"
               "{%- if add_generation_prompt -%}<|assistant|>{{- '<think>' -}}{%- endif -%}")
        d = effort_dialect(src)
        self.assertEqual((d.kind, d.levels, d.default, d.enable_thinking), ("glm", ("low", "high", "max"), "max", False))


class TemplateAtStart(unittest.TestCase):
    """The server names the template's dialect at start and refuses the bundled Qwen template for a real engine
    (before the model loads); a GLM-5.3 run config serves /v1/chat/completions - with the fake engine."""

    def start(self, d: Path, template: Path | None, extra_env=None):
        tok_dir = glm_tokenizer_dir(glm53_pack(d / "pack") / "tokenizer", template)
        tok = glm_tokenizer(d / "tok2")
        cfg = glm53_config(d / "pack")
        cfg["exe"] = fake_exe(d)
        cfg["tokenizer"] = str(tok_dir)
        cfg["cwd"] = str(d)
        cfg["log"] = str(d / "engine.log")
        cfg["env"] = dict(cfg["env"], FAKE_ENGINE_DIR=str(d), STRATA_GPU_RELEASE_S="0",
                          FAKE_ENGINE_IDS=",".join(map(str, tok.encode("Some thought.</think>Hello from glm-5.3."))),
                          **(extra_env or {}))
        p = d / "strata-test.json"
        p.write_text(json.dumps(cfg), encoding="utf-8")
        port = free_port()
        env = dict(os.environ)
        proc = subprocess.Popen([sys.executable, str(ROOT / "serve/server.py"), "--engine", "strata", "--config",
                                 str(p), "--port", str(port)], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, cwd=str(d), env=env)
        return proc, port

    def read_until(self, proc, needle, timeout=60):
        out, end = [], time.time() + timeout
        while time.time() < end:
            line = proc.stdout.readline()
            if not line:
                break
            out.append(line)
            if needle in line:
                return "".join(out), True
        return "".join(out), False

    def test_strata_config_serves_chat_completions(self):
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=WIN) as d:
            proc, port = self.start(Path(d), OFFICIAL)
            try:
                text, ok = self.read_until(proc, "ready: http://")
                self.assertTrue(ok, text)
                self.assertIn("GLM-5.3 (glm-dsa), text only; chat template: GLM thinking levels low, high, max", text)
                self.assertIn("the official GLM-5.3 template", text)
                self.assertIn("thinking budget: 12288 tokens", text)
                self.assertIn("layer split across GPUs [0, 1, 2] (26,54)", text)
                self.assertIn("context 65536 tokens", text)
                code, body = post(f"http://127.0.0.1:{port}", "/v1/chat/completions",
                                  {"model": "glm-5.3", "messages": [{"role": "user", "content": "hi"}],
                                   "max_tokens": 4000})          # (under ~1.3K the thinking budget is 1 token)
                self.assertEqual(code, 200, body)
                msg = body["choices"][0]["message"]
                self.assertEqual(msg["content"], "Hello from glm-5.3.")
                self.assertEqual(msg.get("reasoning_content"), "Some thought.")
                self.assertEqual(body["model"], "glm-5.3")
            finally:
                proc.terminate()
                proc.communicate(timeout=60)
            self.assertNotIn("killed", (Path(d) / "engine.log").read_text())

    def test_a_pack_without_a_template_gets_the_official_one(self):
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=WIN) as d:
            proc, port = self.start(Path(d), None)
            try:
                text, ok = self.read_until(proc, "ready: http://")
                self.assertTrue(ok, text)
                self.assertIn("the official GLM-5.3 template", text)    # never Flash's (image slots) nor Qwen's
                # (one answered request before the stop: a SIGTERM in the server's first moments after "ready:" can
                # land while its main loop holds the stop Event's lock - serve/server.py request_stop then waits for
                # it forever, every model alike; this test is not about that)
                with urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=30) as r:
                    self.assertEqual(r.status, 200)
            finally:
                proc.terminate()
                proc.communicate(timeout=60)


