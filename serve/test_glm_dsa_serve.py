def fake_exe(d: Path) -> str:
    """The fake engine as an engine exe: the script itself (its #! line) on POSIX; Windows runs no script by its #!
    line, so there a .bat in `d` starts it with this Python (as serve/test_stop.py does)."""
    if not WIN:
        return str(FAKE)
    bat = Path(d) / "fake-bin" / "glm_dsa_fake_engine.bat"
    bat.parent.mkdir(parents=True, exist_ok=True)
    bat.write_text(f'@"{sys.executable}" "{FAKE}" %*\r\n', encoding="utf-8")
    return str(bat)


def glm53_pack(d: Path) -> Path:
    """A pack folder that says it is GLM-5.3's (the index.txt header tools/strata/glm_dsa_pack.py writes)."""
    d.mkdir(parents=True, exist_ok=True)
    (d / "index.txt").write_text("# strata pack index v3 -- generated by tools/iq_pack.py\n"
                                 "# glm-dsa: trunk 78, dense lead 3, experts 256, mtp yes, indexer full 21\n",
                                 encoding="utf-8")
    return d


def glm53_config(pack: Path) -> dict:
    """A GLM-5.3 run config as setup writes one (3x V100 32 GB, the split at the full-indexer layers 26 / 54)."""
    return {"exe": "build/maya", "args": ["--glm-pack", str(pack), "--max-context", "65536", "--prefill", "auto"],
            "cwd": ".", "tokenizer": str(pack / "tokenizer"), "model_name": "glm-5.3", "gpu": [0, 1, 2],
            "layer_split": "26,54", "sampling": {"temperature": 1.0, "top_p": 0.95}, "reasoning_effort": "high",
            "thinking_budget": 12288, "port": 8080, "log": "maya-glm53.log", "env": {}}

# GLM-5.x's added tokens in id order (its tokenizer.json): type 3 = control (matched with parse_special), 4 = always
GLM_SPECIALS = [("<|endoftext|>", 3), ("[MASK]", 3), ("[gMASK]", 3), ("[sMASK]", 3), ("<sop>", 3), ("<eop>", 3),
                ("<|system|>", 3), ("<|user|>", 3), ("<|assistant|>", 3), ("<|observation|>", 3),
                ("<|begin_of_image|>", 3), ("<|end_of_image|>", 3), ("<|begin_of_video|>", 3),
                ("<|end_of_video|>", 3), ("<|begin_of_audio|>", 3), ("<|end_of_audio|>", 3),
                ("<|begin_of_transcription|>", 3), ("<|end_of_transcription|>", 3), ("<|code_prefix|>", 4),
                ("<|code_middle|>", 4), ("<|code_suffix|>", 4), ("<think>", 4), ("</think>", 4), ("<tool_call>", 4),
                ("</tool_call>", 4), ("<tool_response>", 4), ("</tool_response>", 4), ("<arg_key>", 4),
                ("</arg_key>", 4), ("<arg_value>", 4), ("</arg_value>", 4), ("/nothink", 4),
                ("<|begin_of_box|>", 4), ("<|end_of_box|>", 4), ("<|image|>", 4), ("<|video|>", 4)]


def glm_tokenizer_dir(d: Path, template: Path | None = OFFICIAL) -> Path:
    """A pack tokenizer/ folder with GLM's specials over the 256 byte tokens (no merges: one token a byte), the
    files tools/strata_tokenizer.py reads, and the chat template (None: none, as a pack that lost it)."""
    import strata_tokenizer as ST
    d.mkdir(parents=True, exist_ok=True)
    byte = ST.bytes_to_unicode()
    rare = byte[0] + " " + byte[1]                       # one merge (of two control bytes) for a well-formed file
    tokens = [byte[b] for b in range(256)] + [t for t, _ in GLM_SPECIALS] + [rare.replace(" ", "")]
    (d / "vocab.json").write_text(json.dumps({t: i for i, t in enumerate(tokens)}), encoding="utf-8")
    (d / "merges.txt").write_text(rare, encoding="utf-8")
    (d / "token_type.json").write_text(json.dumps([1] * 256 + [ty for _, ty in GLM_SPECIALS] + [1]))
    (d / "tokenizer.json").write_text(json.dumps({"pre": "glm4"}))
    if template is not None:
        shutil.copy(template, d / "chat_template.jinja")
    return d


def glm_tokenizer(d: Path):
    import strata_tokenizer as ST
    return ST.Tokenizer.from_dir(glm_tokenizer_dir(d))


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def post(base, path, body, timeout=60):
    req = urllib.request.Request(base + path, data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, json.loads(r.read())
    except urllib.error.HTTPError as e:
        with e:
            return e.code, json.loads(e.read())


def system_line(prompt: str) -> str:
    m = re.search(r"<\|system\|>Reasoning Effort: (\w+)", prompt)
    return m.group(1) if m else ""


