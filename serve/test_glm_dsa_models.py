def g53_cfg(d: Path, name="maya-glm-5.3-ud-iq2_m.json", kv_streaming="off", **extra) -> Path:
    """A GLM-5.3 config as the setup writes it (an older setup's: kv_streaming "on")."""
    pack = d / "GLM-5.3-UD-IQ2_M" / "pack"
    pack.mkdir(parents=True, exist_ok=True)
    (pack / "index.txt").write_text(INDEX, encoding="utf-8")
    (pack.parent / "GLM-5.3-UD-IQ2_M-00001-of-00006.gguf").write_bytes(b"x" * 1000)
    args = ["--glm-pack", str(pack), "--max-context", "65536", "--expert-cache", "auto", "--prefill", "auto"]
    if kv_streaming:
        args += ["--kv-streaming", kv_streaming]
    cfg = {"exe": "/b/maya", "args": args, "model_name": "glm-5.3", "gpu": [0, 1, 2], "port": 8080,
           "sampling": {"temperature": 1.0, "top_p": 0.95}, "reasoning_effort": "max",
           "installer": {"models_dir": str(d), "quant": "GLM-5.3-UD-IQ2_M", "draft": "mtp",
                         "written": "2026-11-07 03:00"}, **extra}
    p = d / name
    p.write_text(json.dumps(cfg, indent=1))
    return p


def flash_cfg(d: Path, name="maya-maya-m.json", **extra) -> Path:
    """GLM-5.3-Flash's config as serve/test_models.py's glm_cfg writes it (its pack: Flash's header, no glm-dsa line)."""
    pack = d / "GLM-5.3-Flash" / "Maya-M" / "pack"
    pack.mkdir(parents=True, exist_ok=True)
    (pack / "index.txt").write_text("# strata pack index v3 -- generated by tools/iq_pack.py from x.gguf\n"
                                    "output.weight 0 0 0 0 0 0 6144 154880 8 0 32 0 0 0 0 0 0 0\n", encoding="utf-8")
    (pack.parent / "shard.gguf").write_bytes(b"x" * 1000)
    cfg = {"exe": "/b/maya", "args": ["--glm-pack", str(pack), "--max-context", "131072", "--expert-cache", "auto",
                                      "--prefill", "auto", "--kv-streaming", "on"],
           "model_name": "glm-5.3-flash", "gpu": [0, 1], "port": 8080, "vision": {"mmproj": "/v/mmproj.gguf"},
           "env": {"MAYA_GLM_RAM_HEADROOM_GB": "4"}, "sampling": {"temperature": 1.0},
           "installer": {"models_dir": str(d), "quant": "Maya-M", "draft": "mtp", "written": "2026-10-20 09:00"},
           **extra}
    p = d / name
    p.write_text(json.dumps(cfg, indent=1))
    return p


