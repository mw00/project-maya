class CacheBytes(Base):
    """b) The Context size's line: GLM-5.3's cache a token from its pack (GLM-5.3-Flash's 12 KB stays the page's own)."""

    def test_geometry_and_bytes(self):
        pack = M.pack_of(M.read(self.g53))
        self.assertEqual(G53.geometry(pack), {"trunk": 78, "mtp": True, "full": 21, "kv_lora": 512, "kv_row": 576,
                                              "idx_key": 128})
        # 79 layers x (544 B INT8 latent + 128 B k_pe) + 22 index-key layers x 512 B (FP32)
        self.assertEqual(G53.kv_bytes_per_token(pack), 79 * 672 + 22 * 512)
        self.assertEqual(G53.kv_bytes_per_token(pack), G53.KV_BYTES)                 # (the setup's estimate)
        self.assertEqual(G53.kv_bytes_per_token(pack, int8=False), 79 * 1152 + 22 * 512)
        self.assertEqual(G53.kv_bytes_per_token(pack, idx_fp16=True), 79 * 672 + 22 * 256)
        # the engine's own count on GPU day 1: 0.98 GB of state/KV at 16384 positions on 3 GPUs
        self.assertAlmostEqual(16384 * G53.KV_BYTES / 2**30, 0.33 + 0.34 + 0.31, delta=0.02)
        self.assertIsNone(G53.kv_bytes_per_token(M.pack_of(M.read(self.flash))))
        self.assertIsNone(G53.kv_bytes_per_token(self.d / "nowhere"))

    def test_the_configs_formats(self):
        cfg = M.read(self.g53)
        self.assertEqual(M.glm53_kv_bytes(cfg), 64352)
        fp16 = 79 * 1152 + 22 * 512
        self.assertEqual(M.glm53_kv_bytes(dict(cfg, env={"MAYA_GLM_KV_INT8": "0"})), fp16)
        self.assertEqual(M.glm53_kv_bytes(dict(cfg, args=cfg["args"] + ["--kv", "fp16"])), fp16)
        self.assertEqual(M.glm53_kv_bytes(dict(cfg, args=cfg["args"] + ["--kv", "fp16"],
                                               env={"STRATA_GLM_KV_INT8": "1"})), 64352)   # (the environment wins)
        self.assertEqual(M.glm53_kv_bytes(dict(cfg, env={"MAYA_GLM_IDX_FP16": "1"})), 79 * 672 + 22 * 256)
        self.assertIsNone(M.glm53_kv_bytes(M.read(self.flash)))


